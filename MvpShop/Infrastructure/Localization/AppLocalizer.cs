    public string CurrentLanguage
    {
        get
        {
            var value = httpContextAccessor.HttpContext?.Request.Cookies[CookieName];
            return value == Russian ? Russian : Mongolian;
        }
    }

    public bool IsRussian => CurrentLanguage == Russian;

    public string T(string key)
    {
        var source = IsRussian ? RussianTexts : MongolianTexts;
        return source.TryGetValue(key, out var value) ? value : key;
    }

    public string F(string key, params object[] args) => string.Format(T(key), args);

    public string ProductName(string value)
    {
        if (!IsRussian)
        {
            return value;
        }

        return RussianProductNames.TryGetValue(value, out var translated) ? translated : value;
    }

